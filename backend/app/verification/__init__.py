"""验证运行器包：配对比较的运行前规格、材料绑定与注入前硬失败校验。

设计目的：
- 把配对比较的前置条件集中成可校验的显式规格：缺项、越界或口径不明都在构造阶段失败；
- 两侧身份的构造口径同样是显式输入：不在进程内登记身份，也不按别名或默认值隐式选择；
- 材料只由外部输入提供：本包不生成、不派生、也不缓存任何随机材料；
- 摘要一律由内容重算：冻结清单不是凭据来源，与实际输入不符即失败；
- 本包不含任何可推进牌局的代码：不创建引擎、不注入发牌、不循环提交行动，
  因此不存在可被伪造子类解锁的执行入口。

职责边界：本包只读依赖牌局牌类型、策略层座位风格顺序与复盘参考版本快照，
不读写数据库与文件，不依赖接口层、模型层与持久化层，单进程运行且不含并行。
"""

